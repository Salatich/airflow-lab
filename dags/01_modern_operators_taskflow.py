"""Scenario 1: Modern Operators & Dynamic Task Mapping.

Combines TaskFlow API (@task, @task.branch) with classic operators
(BashOperator, PythonOperator, EmptyOperator), demonstrating dynamic task
mapping (expand()) to achieve runtime parallelization without hardcoded tasks.

Assessment Focus:
- TaskFlow API vs Classic Operator interoperability.
- Dynamic Task Mapping (expand() and partial()).
- Fan-out / Fan-in Map-Reduce aggregation pattern.
- Conditional branching with @task.branch.
"""

from __future__ import annotations

import logging
from datetime import datetime, timedelta
from typing import Any

from airflow.decorators import dag, task
from airflow.operators.bash import BashOperator
from airflow.operators.empty import EmptyOperator
from airflow.operators.python import PythonOperator

logger = logging.getLogger("airflow.task")

default_args = {
    "owner": "data-engineering",
    "depends_on_past": False,
    "email_on_failure": False,
    "email_on_retry": False,
    "retries": 1,
    "retry_delay": timedelta(seconds=15),
}


@dag(
    dag_id="01_modern_operators_dynamic_mapping",
    default_args=default_args,
    description="Mix of TaskFlow API, Classic Operators, and Dynamic Task Mapping (expand)",
    start_date=datetime(2026, 1, 1),
    schedule=None,  # Manual / API triggered
    catchup=False,
    tags=["lead-de", "taskflow", "dynamic-mapping", "core-scenarios"],
)
def modern_operators_pipeline():
    """Workflow exhibiting TaskFlow API, dynamic parallelization, and classic operators."""

    # 1. Classic Operator: Workflow start sentinel
    start_pipeline = EmptyOperator(
        task_id="start_pipeline",
    )

    # 2. Classic BashOperator: Environment validation
    audit_environment = BashOperator(
        task_id="audit_environment",
        bash_command="echo '=== Environment Health Check ===' && uname -a || ver",
    )

    # 3. TaskFlow API: Dynamic Partition Discoverer (Generates N partitions dynamically)
    @task(task_id="discover_partitions")
    def discover_partitions() -> list[dict[str, Any]]:
        """Dynamically identifies active partitions requiring ingestion.

        In production, this queries Kafka partition offsets, an S3 bucket listing,
        or a database CDC watermark table.
        """
        partitions = [
            {"partition_id": 101, "region": "us-east", "record_count": 4500},
            {"partition_id": 102, "region": "us-west", "record_count": 7800},
            {"partition_id": 103, "region": "eu-west", "record_count": 12400},
            {"partition_id": 104, "region": "ap-southeast", "record_count": 3100},
        ]
        logger.info("Discovered %d dynamic partitions for parallel execution.", len(partitions))
        return partitions

    discovered_partitions = discover_partitions()

    # 4. Dynamic Task Mapping: expand() spawns 1 task instance per discovered partition at runtime!
    @task(task_id="process_partition", max_active_tis_per_dag=8)
    def process_partition(partition_meta: dict[str, Any]) -> dict[str, Any]:
        """Worker task mapped dynamically over discovered partitions.

        Demonstrates partial() and expand() concurrency without hardcoded task graphs.
        """
        p_id = partition_meta["partition_id"]
        region = partition_meta["region"]
        records = partition_meta["record_count"]

        logger.info(
            "Processing partition %d for region '%s' (%d records)...", p_id, region, records
        )
        # Transform logic / business computation
        processed_records = records - int(records * 0.02)  # 2% dirty records quarantined
        return {
            "partition_id": p_id,
            "region": region,
            "valid_records": processed_records,
            "quarantined_records": records - processed_records,
        }

    # Dynamically expand process_partition for every partition generated by discover_partitions
    mapped_results = process_partition.expand(partition_meta=discovered_partitions)

    # 5. TaskFlow Fan-In Reducer: Aggregates results from dynamically mapped tasks
    @task(task_id="aggregate_metrics")
    def aggregate_metrics(results: list[dict[str, Any]]) -> dict[str, Any]:
        """Fan-in reducer consuming mapped task outputs."""
        total_valid = sum(r["valid_records"] for r in results)
        total_quarantined = sum(r["quarantined_records"] for r in results)
        logger.info(
            "Fan-in Aggregation: %d valid records, %d quarantined across %d partitions.",
            total_valid,
            total_quarantined,
            len(results),
        )
        return {
            "total_valid_records": total_valid,
            "total_quarantined_records": total_quarantined,
            "partitions_processed": len(results),
            "status": "HEALTHY" if total_valid > 10000 else "DEGRADED",
        }

    aggregated_summary = aggregate_metrics(mapped_results)

    # 6. TaskFlow Branching (@task.branch)
    @task.branch(task_id="evaluate_data_volume")
    def evaluate_data_volume(summary: dict[str, Any]) -> str:
        """Evaluates batch health and branches downstream path conditionally."""
        if summary["total_valid_records"] >= 20000:
            logger.info("High-volume throughput detected. Routing to fast-path loader.")
            return "high_volume_notification"
        else:
            logger.info("Standard-volume throughput. Routing to standard loader.")
            return "standard_volume_notification"

    branch_choice = evaluate_data_volume(aggregated_summary)

    # 7. Downstream Branch Targets (Mixing Classic Operators)
    high_volume_task = BashOperator(
        task_id="high_volume_notification",
        bash_command="echo 'ALERT: High Volume Pipeline Ingestion Complete!'",
    )

    def _classic_python_log(**context):
        task_instance = context["ti"]
        summary = task_instance.xcom_pull(task_ids="aggregate_metrics")
        logger.info("Classic PythonOperator executed. Batch Summary: %s", summary)

    standard_volume_task = PythonOperator(
        task_id="standard_volume_notification",
        python_callable=_classic_python_log,
    )

    # 8. Pipeline Terminal Sentinel (trigger_rule='none_failed_min_one_success' for branching)
    end_pipeline = EmptyOperator(
        task_id="end_pipeline",
        trigger_rule="none_failed_min_one_success",
    )

    # Task Graph Wiring
    start_pipeline >> audit_environment >> discovered_partitions
    # Dynamic expansion mapped_results automatically depends on discovered_partitions
    # aggregate_metrics automatically depends on mapped_results
    aggregated_summary >> branch_choice >> [high_volume_task, standard_volume_task] >> end_pipeline


modern_operators_pipeline_dag = modern_operators_pipeline()
